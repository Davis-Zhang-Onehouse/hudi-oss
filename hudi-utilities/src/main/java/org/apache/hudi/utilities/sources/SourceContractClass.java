package org.apache.hudi.utilities.sources;

import java.lang.annotation.ElementType;
import java.lang.annotation.Inherited;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Names the {@link SourceContract} of a source class; a subclass inherits it. The contract class must have a public constructor
 * taking the job's {@code TypedProperties}.
 */
@Inherited
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
public @interface SourceContractClass {

  /** The source's contract. */
  Class<? extends SourceContract> value();
}
